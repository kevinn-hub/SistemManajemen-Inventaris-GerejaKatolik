            efisien. Sistem ini memungkinkan pengurus gereja untuk melakukan pencatatan,
            pengelompokan, pemantauan, serta pelaporan data inventaris dalam satu platform
            yang terintegrasi.
        </p>

        <p style="text-align: justify;">
